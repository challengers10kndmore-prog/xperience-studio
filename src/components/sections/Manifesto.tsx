import { useMemo, useRef, type ReactNode } from "react";
import { useSiteData } from "@/data/DataProvider";
import { siteProjects, artFor } from "@/data/placeholders";
import { gsap, useGSAP } from "@/motion/gsap";
import { hasFinePointer, reducedMotion } from "@/motion/useReducedMotion";
import { useCompact } from "@/hooks/useInView";
import { mediaUrl } from "@/lib/media";
import { isLite } from "@/lib/perf";
import { XperienceLogo } from "@/components/brand/XperienceLogo";

const DEFAULT_LINES = [
  "AI gives me a thousand shots.", "Most of them are noise.", "Editing finds the twelve that matter:",
  "the cut, the pause, the beat that lands.", "Generated by machines. Directed by instinct. Cut by hand.", "This is the Xperience.",
];

/** Splits `line` around the first match of `re`, wrapping the match with `wrap`. */
function mark(line: string, re: RegExp, wrap: (m: string) => ReactNode): ReactNode {
  const m = line.match(re);
  if (!m || m.index === undefined) return line;
  return <>{line.slice(0, m.index)}{wrap(m[0])}{line.slice(m.index + m[0].length)}</>;
}

/**
 * Manifesto: six lines revealed one at a time while the section stays pinned.
 * 1 "a thousand" counts 0 -> 1,000 while a 3D tunnel of real film frames streams toward the camera.
 * 2 the frames lose focus and fall away; "noise" glitches with an RGB split.
 * 3 twelve frames lock into a floating 3D grid that turns with the cursor; "twelve" glows in the brand gradient.
 * 4 "the cut" (hard cut), "the pause" (held frame, letterbox), "the beat" (pulse) each land on a beat.
 * 5 the three phrases build as extruded chrome type, one per beat.
 * 6 "Xperience" resolves in the logo's style with the brand light sweep; then the section releases.
 * Phones: same story, vertical layout, fewer frames, no heavy blur. Reduced motion: the lines, no pin.
 */
export function Manifesto() {
  const data = useSiteData();
  const compact = useCompact();
  const root = useRef<HTMLElement>(null);
  const lines = useMemo(() => {
    const ls = data.settings.copy.manifesto.text.split(/\n+/).map((l) => l.trim()).filter(Boolean);
    return ls.length >= 6 ? ls.slice(0, 6) : DEFAULT_LINES;
  }, [data.settings.copy.manifesto.text]);
  const posters = useMemo(() => {
    const ps = siteProjects(data.projects);
    return ps.map((p) => ({ src: p.poster_url ? mediaUrl(p.poster_url) : undefined, bg: artFor(p.id, p.discipline) }));
  }, [data.projects]);
  const lite = isLite();
  const nFrames = lite ? 36 : compact ? 48 : 140;
  const frames = useMemo(() => Array.from({ length: nFrames }, (_, i) => {
    const a = (i * 137.508 * Math.PI) / 180; // golden angle: even spread around the tunnel
    return { a, r: 0.45 + ((i * 7919) % 100) / 180, z: ((i * 104729) % 1000) / 1000, p: posters.length ? posters[i % posters.length] : { bg: "#100E1A" } };
  }), [nFrames, posters]);
  const twelve = useMemo(() => Array.from({ length: 12 }, (_, i) => posters.length ? posters[(i * 5) % posters.length] : { bg: artFor(`g${i}`, i % 2 ? "ai" : "editing") }), [posters]);
  const phrases5 = lines[4].split(/(?<=\.)\s+/).filter(Boolean);
  const beats = lines[3];
  const thousand = /a thousand/i;

  useGSAP(() => {
    const el = root.current!;
    const q = gsap.utils.selector(el);
    if (reducedMotion()) {
      gsap.from(q("[data-line]"), { opacity: 0, duration: 0.6, stagger: 0.1, scrollTrigger: { trigger: el, start: "top 75%" } });
      return;
    }
    // ---------- shared state read by the frame loop ----------
    const S = { tunnel: 1, speed: 1, fall: 0, glitch: 0, grid: 0, spin: 1, held: 0 };
    const tunnelFrames = q<HTMLElement>("[data-tf]");
    const tunnel = q<HTMLElement>("[data-tunnel]")[0];
    const gridIn = q<HTMLElement>("[data-grid-inner]")[0];
    const noiseCopies = q<HTMLElement>("[data-noise-copy]");
    const W = () => el.clientWidth, H = () => el.clientHeight;
    let t0 = performance.now(), mx = 0, my = 0, running = false, raf = 0;
    const DEPTH = 4200;
    const tick = (now: number) => {
      const t = (now - t0) / 1000;
      const R = Math.min(W(), H()) * (compact ? 0.55 : 0.75);
      // tunnel: frames stream toward the camera; on "noise" they fall away
      if (S.tunnel > 0.01) {
        for (let i = 0; i < tunnelFrames.length; i++) {
          const f = frames[i], node = tunnelFrames[i];
          const z = (((f.z * DEPTH + t * 520 * S.speed) % DEPTH) + DEPTH) % DEPTH - DEPTH + 200;
          const x = Math.cos(f.a) * f.r * R, y = Math.sin(f.a) * f.r * R + S.fall * (500 + (i % 7) * 90);
          const near = (z + DEPTH) / DEPTH; // 0 far .. 1 near
          node.style.transform = `translate3d(${x.toFixed(1)}px, ${y.toFixed(1)}px, ${z.toFixed(0)}px) rotate(${(S.fall * ((i % 5) - 2) * 30).toFixed(1)}deg)`;
          node.style.opacity = (S.tunnel * Math.min(1, near * 1.6) * (1 - S.fall)).toFixed(3);
        }
      }
      if (S.glitch > 0.01) noiseCopies.forEach((c, k) => { c.style.transform = `translate(${((Math.random() - 0.5) * 14 * S.glitch + (k ? 4 : -4) * S.glitch).toFixed(1)}px, ${((Math.random() - 0.5) * 4 * S.glitch).toFixed(1)}px)`; c.style.opacity = String(S.glitch * 0.85); });
      if (gridIn) {
        const spin = S.held ? 0 : Math.sin(t * 0.35) * 8 * S.spin;
        gridIn.style.transform = `rotateY(${(spin + mx * 14).toFixed(2)}deg) rotateX(${(8 - my * 10).toFixed(2)}deg)`;
      }
      raf = requestAnimationFrame(tick);
    };
    const run = (on: boolean) => { if (on && !running) { running = true; t0 = performance.now() - 0; raf = requestAnimationFrame(tick); } else if (!on && running) { running = false; cancelAnimationFrame(raf); } };
    const move = (e: PointerEvent) => { mx = e.clientX / innerWidth - 0.5; my = e.clientY / innerHeight - 0.5; };
    if (hasFinePointer()) window.addEventListener("pointermove", move, { passive: true });

    // ---------- the scroll story ----------
    const lineEls = q<HTMLElement>("[data-line]");
    gsap.set(lineEls, { autoAlpha: 0 });
    const count = { v: 0 };
    const counter = q<HTMLElement>("[data-count]")[0];
    const lineIn = (i: number, at: number) => tl.fromTo(lineEls[i], { autoAlpha: 0, y: 40, rotateX: -50 }, { autoAlpha: 1, y: 0, rotateX: 0, duration: 0.5, ease: "power3.out" }, at);
    const lineOut = (i: number, at: number) => tl.to(lineEls[i], { autoAlpha: 0, y: -40, rotateX: 40, duration: 0.4, ease: "power2.in" }, at);
    const tl = gsap.timeline({
      defaults: { ease: "none" },
      scrollTrigger: { trigger: el, start: "top top", end: compact ? "+=520%" : "+=680%", pin: true, scrub: 0.8, anticipatePin: 1, onToggle: (s) => run(s.isActive), onEnter: () => run(true) },
    });
    // 1 - a thousand shots
    lineIn(0, 0);
    tl.fromTo(tunnel, { opacity: 0, scale: 0.8 }, { opacity: 1, scale: 1, duration: 0.6 }, 0)
      .to(count, { v: 1000, duration: 1.8, ease: "power2.in", onUpdate: () => { if (counter) counter.textContent = Math.round(count.v).toLocaleString("en-US"); } }, 0.2)
      .to(S, { speed: 3.2, duration: 1.8, ease: "power2.in" }, 0.2)
      .to(q("[data-count-wrap]"), { autoAlpha: 0, yPercent: -40, duration: 0.25 }, 2.15)
      .fromTo(q("[data-thousand]"), { autoAlpha: 0, yPercent: 40 }, { autoAlpha: 1, yPercent: 0, duration: 0.25 }, 2.2);
    lineOut(0, 2.6);
    // 2 - noise
    lineIn(1, 2.9);
    tl.to(S, { speed: 0.4, fall: 1, duration: 1.3, ease: "power2.in" }, 3.0)
      .to(tunnel, { filter: lite || compact ? "none" : "blur(8px)", duration: 1.3 }, 3.0)
      .to(S, { glitch: 1, duration: 0.15 }, 3.1).to(S, { glitch: 0.6, duration: 0.9 }, 3.25).to(S, { glitch: 0, duration: 0.2 }, 4.2)
      .set(S, { tunnel: 0 }, 4.4);
    lineOut(1, 4.3);
    // 3 - twelve frames lock into a 3D grid
    lineIn(2, 4.6);
    tl.fromTo(q("[data-gc]"), { z: -1400, opacity: 0, rotateY: (i: number) => (i % 2 ? 40 : -40) }, { z: 0, opacity: 1, rotateY: 0, duration: 0.9, stagger: 0.05, ease: "expo.out" }, 4.7)
      .fromTo(q("[data-twelve]"), { filter: "drop-shadow(0 0 0px rgba(200,75,255,0))" }, { filter: "drop-shadow(0 0 22px rgba(200,75,255,.85))", duration: 0.5 }, 5.2);
    lineOut(2, 6.0);
    // 4 - the cut / the pause / the beat
    lineIn(3, 6.25);
    gsap.set(q("[data-beat]"), { autoAlpha: 0 });
    tl.to(q("[data-beat='0']"), { autoAlpha: 1, duration: 0.05 }, 6.5)
      .fromTo(q("[data-flash]"), { opacity: 0 }, { opacity: 1, duration: 0.02 }, 6.5).to(q("[data-flash]"), { opacity: 0, duration: 0.12 }, 6.53)
      .to(q("[data-grid]"), { x: compact ? 14 : 48, duration: 0.02 }, 6.52).to(q("[data-grid]"), { x: 0, duration: 0.02 }, 6.9) // hard cut: the grid jumps
      .to(q("[data-beat='1']"), { autoAlpha: 1, duration: 0.2 }, 7.1)
      .to(S, { held: 1, duration: 0.01 }, 7.1)
      .fromTo(q("[data-bar]"), { scaleY: 0 }, { scaleY: 1, duration: 0.3, ease: "power3.out" }, 7.1)
      .fromTo(q("[data-hold]"), { autoAlpha: 0 }, { autoAlpha: 1, duration: 0.1 }, 7.15)
      .to(q("[data-beat='2']"), { autoAlpha: 1, duration: 0.05 }, 7.7)
      .to(S, { held: 0, duration: 0.01 }, 7.7).to(q("[data-hold]"), { autoAlpha: 0, duration: 0.1 }, 7.7)
      .fromTo(q("[data-grid]"), { scale: 1.09 }, { scale: 1, duration: 0.35, ease: "elastic.out(1, 0.4)" }, 7.7)
      .fromTo(q("[data-ring]"), { scale: 0.2, opacity: 0.9 }, { scale: 3, opacity: 0, duration: 0.6, ease: "power2.out" }, 7.7)
      .to(q("[data-beat='3']"), { autoAlpha: 1, duration: 0.2 }, 8.0);
    lineOut(3, 8.5);
    tl.to(q("[data-bar]"), { scaleY: 0, duration: 0.3 }, 8.5)
      .to(q("[data-grid]"), { opacity: 0.12, scale: 0.8, x: 0, duration: 0.5 }, 8.5);
    // 5 - extruded chrome phrases, one per beat
    lineIn(4, 8.8);
    tl.fromTo(q("[data-chrome]"), { autoAlpha: 0, yPercent: 80, rotateX: -80 }, { autoAlpha: 1, yPercent: 0, rotateX: 0, duration: 0.45, stagger: 0.55, ease: "back.out(1.6)" }, 8.9);
    lineOut(4, 10.9);
    // 6 - This is the Xperience
    lineIn(5, 11.2);
    tl.to(q("[data-grid]"), { opacity: 0, duration: 0.3 }, 11.1)
      .fromTo(q("[data-xp-l]"), { autoAlpha: 0, yPercent: 100, rotateX: -80 }, { autoAlpha: 1, yPercent: 0, rotateX: 0, stagger: 0.06, duration: 0.5, ease: "expo.out" }, 11.4)
      .fromTo(q("[data-xp-mark]"), { autoAlpha: 0, scale: 0.5, rotate: -90 }, { autoAlpha: 1, scale: 1, rotate: 0, duration: 0.6, ease: "expo.out" }, 11.4)
      .fromTo(q("[data-sweep]"), { xPercent: -110 }, { xPercent: 110, duration: 0.8, ease: "power2.inOut" }, 11.9)
      .fromTo(q("[data-sweep-inner]"), { xPercent: 110 }, { xPercent: -110, duration: 0.8, ease: "power2.inOut" }, 11.9)
      .to({}, { duration: 0.6 });
    return () => { run(false); window.removeEventListener("pointermove", move); };
  }, { scope: root, dependencies: [lines.join("|"), compact, nFrames], revertOnUpdate: true });

  const Frame = ({ p, className = "", ...rest }: { p: { src?: string; bg: string }; className?: string; [k: string]: unknown }) => (
    <div {...rest} className={`overflow-hidden rounded-md border border-chrome/15 ${className}`} style={{ background: p.bg }}>
      {p.src && <img src={p.src} alt="" loading="lazy" decoding="async" className="h-full w-full object-cover" />}
    </div>
  );
  const cols = compact ? 3 : 4;
  const typeLine = "font-display font-semibold leading-[1.02] text-[clamp(1.9rem,1rem+4.4vw,5.6rem)] text-balance";
  return (
    <div>
      <section ref={root} id="manifesto" data-offscreen-ok aria-label="Manifesto" className="relative h-svh overflow-hidden bg-void">
        <p className="sr-only">{lines.join(" ")}</p>
        {/* 1-2: tunnel of frames */}
        <div data-tunnel aria-hidden className="pointer-events-none absolute inset-0 [perspective:900px]">
          <div className="absolute left-1/2 top-1/2 [transform-style:preserve-3d]">
            {frames.map((f, i) => (
              <Frame key={i} data-tf p={f.p} className="absolute -left-[60px] -top-[34px] h-[68px] w-[120px] will-change-transform max-md:-left-[40px] max-md:-top-[23px] max-md:h-[45px] max-md:w-[80px]" />
            ))}
          </div>
        </div>
        {/* 3-4: the twelve */}
        {/* full-width, transform-free positioning so GSAP owns the grid's transform */}
        <div aria-hidden className={`pointer-events-none absolute inset-x-0 flex justify-center ${compact ? "top-[38%]" : "top-[38%]"}`}>
          <div data-grid className={`relative [perspective:1100px] ${compact ? "w-[86vw]" : "w-[min(62vw,980px)]"}`}>
            <div data-grid-inner className="grid gap-[1.2vmin] [transform-style:preserve-3d]" style={{ gridTemplateColumns: `repeat(${cols}, minmax(0, 1fr))` }}>
              {twelve.map((p, i) => <Frame key={i} data-gc p={p} className="aspect-video opacity-0 shadow-[0_20px_50px_-20px_rgba(124,58,237,.7)]" />)}
            </div>
            <span className="absolute inset-0 grid place-items-center"><span data-ring className="block size-40 rounded-full border-2 border-magenta opacity-0 shadow-[0_0_40px_#C84BFF]" /></span>
          </div>
        </div>
        <div aria-hidden className="pointer-events-none absolute inset-0 z-[5] bg-[radial-gradient(ellipse_55%_40%_at_50%_42%,rgba(7,6,13,.78),rgba(7,6,13,.25)_70%,transparent)]" />
        {/* letterbox (the pause), flash (the cut) */}
        <span data-bar aria-hidden className="pointer-events-none absolute inset-x-0 top-0 z-[6] h-[11svh] origin-top scale-y-0 bg-black" />
        <span data-bar aria-hidden className="pointer-events-none absolute inset-x-0 bottom-0 z-[6] h-[11svh] origin-bottom scale-y-0 bg-black" />
        <span data-hold aria-hidden className="timecode pointer-events-none absolute right-[var(--gutter)] top-[13svh] z-[7] text-sm text-chrome opacity-0">❚❚ HOLD 00:00:07:12</span>
        <span data-flash aria-hidden className="pointer-events-none absolute inset-0 z-[8] bg-white opacity-0" />

        {/* the six lines */}
        <div aria-hidden className={`pointer-events-none absolute inset-x-0 z-10 px-[var(--gutter)] text-center [perspective:900px] ${compact ? "top-[18svh]" : "top-[16svh]"}`}>
          <div className="relative mx-auto max-w-6xl">
            <p data-line className={`${typeLine} absolute inset-x-0`}>
              {mark(lines[0], thousand, () => (
                <span className="relative inline-block">
                  <span data-count-wrap className="timecode absolute inset-x-0 bottom-0 text-center text-magenta"><span data-count>0</span></span>
                  <span data-thousand className="inline-block opacity-0">a thousand</span>
                </span>
              ))}
            </p>
            <p data-line className={`${typeLine} absolute inset-x-0`}>
              {mark(lines[1], /noise/i, (m) => (
                <span className="relative inline-block">
                  <span data-noise-copy className="absolute inset-0 text-[#ff2a6d] opacity-0 mix-blend-screen">{m}</span>
                  <span data-noise-copy className="absolute inset-0 text-[#2af5ff] opacity-0 mix-blend-screen">{m}</span>
                  <span className="relative">{m}</span>
                </span>
              ))}
            </p>
            <p data-line className={`${typeLine} absolute inset-x-0`}>{mark(lines[2], /twelve/i, (m) => <span data-twelve className="text-gradient inline-block">{m}</span>)}</p>
            <p data-line className={`${typeLine} absolute inset-x-0`}>
              {(() => {
                const parts = beats.split(/(the cut,?|the pause,?|the beat)/i).filter(Boolean);
                let k = -1;
                return parts.map((part, i) => /^(the cut|the pause|the beat)/i.test(part)
                  ? <span key={i} data-beat={String(++k)} className="inline-block">{part}</span>
                  : <span key={i} data-beat={/\w/.test(part) ? "3" : undefined} className="inline-block whitespace-pre">{part}</span>);
              })()}
            </p>
            <div data-line className="absolute inset-x-0 space-y-[0.15em] [perspective:900px]">
              {phrases5.map((ph, i) => <p key={i} data-chrome className="chrome-phrase">{ph}</p>)}
            </div>
            <div data-line className="absolute inset-x-0">
              <p className="font-display text-[clamp(1.4rem,1rem+2vw,2.6rem)] font-medium text-chrome/80">{lines[5].replace(/xperience\.?/i, "").trim()}</p>
              <div className="mt-3 flex items-center justify-center gap-[0.25em] [perspective:900px]">
                <span data-xp-mark className="inline-block w-[clamp(3rem,2rem+5vw,7rem)]"><XperienceLogo variant="mark" className="w-full drop-shadow-[0_0_24px_rgba(124,58,237,.6)]" /></span>
                <span className="relative inline-block overflow-hidden">
                  <span className="flex">{[..."XPERIENCE"].map((c, i) => <span key={i} data-xp-l className="chrome-letter !text-[clamp(2.8rem,1rem+8vw,9.5rem)]">{c}</span>)}</span>
                  <span data-sweep className="pointer-events-none absolute inset-0 overflow-hidden [mask-image:linear-gradient(90deg,transparent,#000_30%,#000_70%,transparent)]">
                    <span data-sweep-inner className="flex">{[..."XPERIENCE"].map((c, i) => <span key={i} className="text-gradient font-display text-[clamp(2.8rem,1rem+8vw,9.5rem)] font-bold leading-[0.9] tracking-[-0.02em]">{c}</span>)}</span>
                  </span>
                </span>
              </div>
            </div>
          </div>
        </div>
      </section>
    </div>
  );
}
